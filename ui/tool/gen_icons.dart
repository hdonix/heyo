// Writes lib/widgets/raycast_icons.g.dart: the names extensions give icons
// (Raycast's `Icon`), for Flutter.
//
// The web view draws those with lucide-react: a name is looked up in
// `src/raycast/iconAliases.ts`, and one not listed there is taken to be the
// Lucide icon of the same name. Here the same two steps need two tables,
// since Dart cannot find a constant by its name: the aliases, read from
// that very file, and every icon of the `lucide_icons_flutter` package by
// name.
//
//   dart run tool/gen_icons.dart          writes the file
//   dart run tool/gen_icons.dart --check  fails if it is not up to date
//
// Run it after changing iconAliases.ts or the package's version
// (test/widgets/raycast_icons_test.dart fails until then).

import 'dart:convert';
import 'dart:io';

/// `UserPlus` → `userPlus`: how the Dart package names Lucide's `UserPlus`.
String identifier(String pascal) => pascal[0].toLowerCase() + pascal.substring(1);

/// The aliases in iconAliases.ts: Raycast's name → Lucide's, as written there.
Map<String, String> readAliases(String source) {
  final entry = RegExp(r'''^\s*(?:"([^"]+)"|([a-z0-9-]+)):\s*"([A-Za-z0-9]+)",?\s*$''', multiLine: true);
  return {for (final match in entry.allMatches(source)) (match.group(1) ?? match.group(2))!: match.group(3)!};
}

/// The icons the package has, without the variants it adds to each (other
/// stroke widths, and mirrored ones for right-to-left).
List<String> readIcons(String source) {
  final declared = RegExp(r'static const IconData (\w+) =');
  final variant = RegExp(r'(100|200|300|500|600)(Dir)?$|Dir$');
  return [
    for (final match in declared.allMatches(source))
      if (!variant.hasMatch(match.group(1)!)) match.group(1)!,
  ]..sort();
}

String generate({required String aliasSource, required String packageSource}) {
  final aliases = readAliases(aliasSource);
  final icons = readIcons(packageSource);
  final out = StringBuffer()
    ..writeln('// Generated by tool/gen_icons.dart from src/raycast/iconAliases.ts and the')
    ..writeln('// lucide_icons_flutter package. Do not edit.')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart' show IconData;")
    ..writeln("import 'package:lucide_icons_flutter/lucide_icons.dart';")
    ..writeln()
    ..writeln("/// Raycast icon names (without the `-16` suffix) whose Lucide counterpart")
    ..writeln('/// has a different name, to that name as Dart spells it.')
    ..writeln('const raycastAliases = <String, String>{');
  for (final entry in aliases.entries) {
    out.writeln("  '${entry.key}': '${identifier(entry.value)}',");
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('/// Every Lucide icon, by its name as Dart spells it.')
    ..writeln('const lucideIcons = <String, IconData>{');
  for (final icon in icons) {
    out.writeln("  '$icon': LucideIcons.$icon,");
  }
  out.writeln('};');
  return out.toString();
}

/// Where the package's source is, from the project's package table.
String packageSource(String project) {
  final config = jsonDecode(File('$project/.dart_tool/package_config.json').readAsStringSync()) as Map<String, dynamic>;
  final package = (config['packages'] as List).cast<Map<String, dynamic>>().firstWhere((p) => p['name'] == 'lucide_icons_flutter');
  final root = Uri.parse(package['rootUri'] as String);
  final dir = (root.isAbsolute ? root : Directory('$project/.dart_tool/').uri.resolveUri(root)).toFilePath();
  return File('$dir/lib/lucide_icons.dart').readAsStringSync();
}

void main(List<String> args) {
  final project = Directory.current.path;
  final text = generate(aliasSource: File('$project/../src/raycast/iconAliases.ts').readAsStringSync(), packageSource: packageSource(project));
  final file = File('$project/lib/widgets/raycast_icons.g.dart');
  if (args.contains('--check')) {
    if (!file.existsSync() || file.readAsStringSync() != text) {
      stderr.writeln('lib/widgets/raycast_icons.g.dart is out of date: dart run tool/gen_icons.dart');
      exit(1);
    }
    return;
  }
  file.writeAsStringSync(text);
  stdout.writeln('wrote ${file.path}');
}
